    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String codigoEntrenador = txtCodigoEntrenador.getText().trim();
        
        if (codigoEntrenador.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el código del entrenador");
            return;
        }
        
        // === DEPURACIÓN TEMPORAL ===
    System.out.println("=== INICIO DEPURACIÓN ===");
    System.out.println("Código ingresado: " + codigoEntrenador);
    
    // Obtener ID numérico del entrenador
    int idEntrenador = obtenerIdDeCodigo(codigoEntrenador);
    System.out.println("ID entrenador convertido: " + idEntrenador);
    
    if (idEntrenador == -1) {
        JOptionPane.showMessageDialog(this, "Código de entrenador inválido");
        return;
    }
        
        // Buscar entrenador
    Entrenador entrenador = buscarEntrenadorPorId(idEntrenador);
    if (entrenador == null) {
        JOptionPane.showMessageDialog(this, "Entrenador no encontrado");
        System.out.println("Entrenador NO encontrado con ID: " + idEntrenador);
        return;
    }
    System.out.println("Entrenador encontrado: " + entrenador.getNombre());
    
    // Obtener TODAS las reservas del entrenador (sin fecha específica)
    List<Reserva> todasLasReservas = reservaDAO.listarPorEntrenador(idEntrenador);
    
    System.out.println("Número TOTAL de reservas encontradas: " + todasLasReservas.size());
    for (Reserva r : todasLasReservas) {
        System.out.println("Reserva ID: " + r.getIdReserva() + 
                          ", Fecha: " + r.getFecha() +
                          ", Hora: " + r.getHoraInicio() + " a " + r.getHoraFin() +
                          ", Cliente ID: " + r.getIdCliente());
    }
    System.out.println("=== FIN DEPURACIÓN ===");
    
     
    // Generar reporte COMPLETO del entrenador
    String reporte = generarReporteCompleto(entrenador, todasLasReservas);
    
    // Mostrar resultados
    txtResultados.setText(reporte);
    }//GEN-LAST:event_btnBuscarActionPerformed

