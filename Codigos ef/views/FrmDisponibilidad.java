    private int obtenerIdDeCodigo(String codigo) {
        // Convierte "E001" a 1
        if (codigo.matches("[Ee]\\d+")) {
            return Integer.parseInt(codigo.substring(1));
        }
        return -1;
    }
    
    private String generarReporteCompleto(Entrenador entrenador, List<Reserva> todasLasReservas) {
    StringBuilder sb = new StringBuilder();
    
    // Información del entrenador
    sb.append("=== INFORMACIÓN DEL ENTRENADOR ===\n");
    sb.append("Código: ").append(entrenador.getIdFormateado()).append("\n");
    sb.append("Nombre: ").append(entrenador.getNombre()).append("\n");
    sb.append("Especialidad: ").append(entrenador.getEspecialidad()).append("\n");
    sb.append("Edad: ").append(entrenador.getEdad()).append("\n");
    sb.append("Correo: ").append(entrenador.getCorreo()).append("\n\n");
    
    // TODAS las reservas del entrenador
    sb.append("=== TODAS LAS RESERVAS ===\n");
    if (todasLasReservas.isEmpty()) {
        sb.append("No tiene reservas registradas\n");
    } else {
        for (Reserva r : todasLasReservas) {
            String nombreCliente = obtenerNombreCliente(r.getIdCliente());
            sb.append("📅 ").append(formatearFecha(r.getFecha()))
              .append(" | ⏰ ").append(r.getHoraInicio()).append("-").append(r.getHoraFin())
              .append(" | 👤 ").append(nombreCliente)
              .append(" | #").append(r.getIdReserva())
              .append(" | ").append(r.getComentario()).append("\n");
        }
    }
    
    // Resumen
    sb.append("\n=== RESUMEN ===\n");
    sb.append("Total de reservas: ").append(todasLasReservas.size()).append("\n");
    
    return sb.toString();
}

private String obtenerNombreCliente(int idCliente) {
    for (Cliente cliente : clienteDAO.obtenerClientes()) {
        if (cliente.getId() == idCliente) {
            return cliente.getNombre();
        }
    }
    return "Cliente " + idCliente;
}
    
    private Entrenador buscarEntrenadorPorId(int id) {
        for (Entrenador entrenador : entrenadorDAO.listarEntrenadores()) {
            if (entrenador.getId() == id) {
                return entrenador;
            }
        }
        return null;
    }
    
    private String obtenerFechaActual() {
        // Retorna fecha en formato YYYY-MM-DD (puedes mejorar con DatePicker)
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
        return sdf.format(new java.util.Date());
    }
    
    private String generarReporteDisponibilidad(Entrenador entrenador, List<Reserva> reservas, String fecha) {
        StringBuilder sb = new StringBuilder();
        
        // Información del entrenador
        sb.append("=== INFORMACIÓN DEL ENTRENADOR ===\n");
        sb.append("Código: ").append(entrenador.getIdFormateado()).append("\n");
        sb.append("Nombre: ").append(entrenador.getNombre()).append("\n");
        sb.append("Especialidad: ").append(entrenador.getEspecialidad()).append("\n");
        sb.append("Fecha consultada: ").append(formatearFecha(fecha)).append("\n\n");
        
        sb.append("=== DISPONIBILIDAD ===\n");
        
        // Verificar cada horario
        for (String horario : HORARIOS) {
            String[] partes = horario.split("-");
            String horaInicio = partes[0];
            String horaFin = partes[1];
            
            boolean ocupado = false;
            String infoReserva = "";
            
            // Verificar si hay reserva en este horario
            for (Reserva reserva : reservas) {
                if (reserva.getHoraInicio().equals(horaInicio) && 
                    reserva.getHoraFin().equals(horaFin)) {
                    ocupado = true;
                    infoReserva = " - OCUPADO (Reserva #" + reserva.getIdReserva() + ")";
                    break;
                }
            }
            
            if (ocupado) {
                sb.append("❌ ").append(horario).append(infoReserva).append("\n");
            } else {
                sb.append("✅ ").append(horario).append(" - DISPONIBLE\n");
            }
        }
        
        // Estadísticas
        sb.append("\n=== RESUMEN ===\n");
        int totalHorarios = HORARIOS.length;
        int ocupados = reservas.size();
        int disponibles = totalHorarios - ocupados;
        
        sb.append("Horarios disponibles: ").append(disponibles).append("/").append(totalHorarios).append("\n");
        sb.append("Horarios ocupados: ").append(ocupados).append("/").append(totalHorarios).append("\n");
        
        return sb.toString();
    }
     private String formatearFecha(String fechaMySQL) {
        // Convierte "2024-12-15" a "15/12/2024"
        if (fechaMySQL.contains("-")) {
            String[] partes = fechaMySQL.split("-");
            if (partes.length == 3) {
                return partes[2] + "/" + partes[1] + "/" + partes[0];
            }
        }
        return fechaMySQL;
    }
