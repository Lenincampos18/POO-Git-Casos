    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String textoBusqueda = txtBuscar.getText().trim().toLowerCase();
        
        if (textoBusqueda.isEmpty()) {
            cargarEntrenadores(); // Mostrar todos si no hay búsqueda
            return;
        }
        
        modeloTabla.setRowCount(0); // Limpiar tabla
        List<Entrenador> entrenadores = entrenadorDAO.listarEntrenadores();
        for (Entrenador entrenador : entrenadores) {
            // Buscar en nombre, correo o especialidad
            if (entrenador.getNombre().toLowerCase().contains(textoBusqueda) ||
                entrenador.getCorreo().toLowerCase().contains(textoBusqueda) ||
                entrenador.getEspecialidad().toLowerCase().contains(textoBusqueda)) {
                
                modeloTabla.addRow(new Object[]{
                    entrenador.getIdFormateado(),
                    entrenador.getNombre(),
                    entrenador.getEdad(),
                    entrenador.getCorreo(),
                    entrenador.getEspecialidad()
                });
            }
        }
        if (modeloTabla.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No se encontraron entrenadores con: " + textoBusqueda);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int filaSeleccionada = tblEntrenadores.getSelectedRow();
        
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un entrenador para eliminar");
            return;
        }
        
        // Obtener ID del entrenador seleccionado
        String idEntrenadorStr = modeloTabla.getValueAt(filaSeleccionada, 0).toString();
        int idEntrenador = Integer.parseInt(idEntrenadorStr.substring(1)); // Quitar la "E"
        
        // Obtener nombre para mostrar en confirmación
        String nombreEntrenador = modeloTabla.getValueAt(filaSeleccionada, 1).toString();
        
        int confirmacion = JOptionPane.showConfirmDialog(this,
            "¿Está seguro de eliminar al entrenador:\n" +
            nombreEntrenador + " (" + idEntrenadorStr + ")?",
            "Confirmar Eliminación",
            JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION){
            if (entrenadorDAO.eliminarEntrenador(idEntrenador)){
                JOptionPane.showMessageDialog(this, "Entrenador eliminado exitosamente");
                cargarEntrenadores(); // Recargar tabla
            } else {
                JOptionPane.showMessageDialog(this, 
                    "Error al eliminar el entrenador.\n" +
                    "Puede que tenga reservas asociadas.");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int filaSeleccionada = tblEntrenadores.getSelectedRow();
        
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un entrenador para editar");
            return;
        }
        // Obtener datos del entrenador seleccionado
        String idEntrenadorStr = modeloTabla.getValueAt(filaSeleccionada, 0).toString();
        int idEntrenador = Integer.parseInt(idEntrenadorStr.substring(1));
        String nombreActual = modeloTabla.getValueAt(filaSeleccionada, 1).toString();
        int edadActual = (int) modeloTabla.getValueAt(filaSeleccionada, 2);
        String correoActual = modeloTabla.getValueAt(filaSeleccionada, 3).toString();
        String especialidadActual = modeloTabla.getValueAt(filaSeleccionada, 4).toString();
        
        // Diálogo de edición
        String nuevoNombre = JOptionPane.showInputDialog(this, 
            "Editar Nombre:", nombreActual);
        if (nuevoNombre == null || nuevoNombre.trim().isEmpty()) return;
        
        String nuevaEdadStr = JOptionPane.showInputDialog(this, 
            "Editar Edad:", edadActual);
        if (nuevaEdadStr == null) return;
        
        String nuevoCorreo = JOptionPane.showInputDialog(this, 
            "Editar Correo:", correoActual);
        if (nuevoCorreo == null || nuevoCorreo.trim().isEmpty()) return;
        
        String nuevaEspecialidad = JOptionPane.showInputDialog(this, 
            "Editar Especialidad:", especialidadActual);
        if (nuevaEspecialidad == null || nuevaEspecialidad.trim().isEmpty()) return;
        
        // Validar edad
        int nuevaEdad;
        try {
            nuevaEdad = Integer.parseInt(nuevaEdadStr);
            if (nuevaEdad < 1 || nuevaEdad > 120) {
                JOptionPane.showMessageDialog(this, "La edad debe estar entre 1 y 120 años");
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La edad debe ser un número válido");
            return;
        }
        
        // Crear entrenador actualizado y guardar
        Entrenador entrenadorActualizado = new Entrenador(
            idEntrenador, nuevoNombre.trim(), nuevaEdad, nuevoCorreo.trim(), nuevaEspecialidad.trim()
        );
        
        if (entrenadorDAO.actualizarEntrenador(entrenadorActualizado)) {
            JOptionPane.showMessageDialog(this, "Entrenador actualizado exitosamente");
            cargarEntrenadores(); // Recargar tabla
        } else {
            JOptionPane.showMessageDialog(this, "Error al actualizar el entrenador");
        }
        
    }//GEN-LAST:event_btnEditarActionPerformed

