    private void configurarTabla() {
        modeloTabla = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Tabla de solo lectura
            }
        };
        
        // Columnas de la tabla (con Especialidad)
        modeloTabla.addColumn("ID");
        modeloTabla.addColumn("Nombre");
        modeloTabla.addColumn("Edad");
        modeloTabla.addColumn("Correo");
        modeloTabla.addColumn("Especialidad");
        
        tblEntrenadores.setModel(modeloTabla);
    }
    
    private void cargarEntrenadores() {
        modeloTabla.setRowCount(0); // Limpiar tabla
        
        List<Entrenador> entrenadores = entrenadorDAO.listarEntrenadores();
        
        for (Entrenador entrenador : entrenadores) {
            modeloTabla.addRow(new Object[]{
                entrenador.getIdFormateado(),
                entrenador.getNombre(),
                entrenador.getEdad(),
                entrenador.getCorreo(),
                entrenador.getEspecialidad()
            });
        }
    }

