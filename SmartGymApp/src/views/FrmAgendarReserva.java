    private void btnAgendarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgendarActionPerformed
        // Validar selección de cliente
        if (comboClientes.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un cliente");
            return;
        }
        
        // Validar selección de entrenador
        if (comboEntrenadores.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un entrenador");
            return;
        }
        
        // Validar fecha
        String fecha = txtFecha.getText().trim();
    if (fecha.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese la fecha");
        return;
    }
        
        // Validar formato de fecha (dd/mm/aaaa)
        if (!fecha.matches("\\d{2}/\\d{2}/\\d{4}")) {
        JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use dd/mm/aaaa");
        return;
    }
        // CONVERTIR formato dd/mm/aaaa a aaaa-mm-dd para MySQL
    String fechaMySQL = convertirFechaAMySQL(fecha);
        
        // Validar horario
        if (comboHorarios.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un horario");
            return;
        }
        
        // Obtener IDs de cliente y entrenador
        int idCliente = obtenerIdDeCombo(comboClientes.getSelectedItem().toString());
        int idEntrenador = obtenerIdDeCombo(comboEntrenadores.getSelectedItem().toString());
        
        // Obtener horarios
        String horarioSeleccionado = comboHorarios.getSelectedItem().toString();
        String horaInicio = obtenerHoraInicio(horarioSeleccionado);
        String horaFin = obtenerHoraFin(horarioSeleccionado);
        
        String comentario = txtComentario.getText().trim();
        
        // Crear y guardar reserva
        Reserva reserva = new Reserva(idCliente, idEntrenador, fechaMySQL, horaInicio, horaFin, comentario);
        
        if (reservaDAO.registrarReserva(reserva)) {
            JOptionPane.showMessageDialog(this, "Reserva agendada exitosamente");
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al agendar la reserva");
        }
    }//GEN-LAST:event_btnAgendarActionPerformed

