    private int obtenerIdDeCombo(String itemCombo) {
        // Extraer el ID numérico del texto del combo (ej: "C001 - Juan" → 1)
        if (itemCombo.contains(" - ")) {
            String idFormateado = itemCombo.split(" - ")[0];
            // Remover letra y obtener número: "C001" → 1
            return Integer.parseInt(idFormateado.substring(1));
        }
        return -1;
    }

    private String obtenerHoraInicio(String horario) {
        switch (horario) {
            case "1. Mañana: 08:00 - 10:00": return "08:00";
            case "2. Mañana: 10:00 - 12:00": return "10:00";
            case "3. Tarde: 14:00 - 16:00": return "14:00";
            case "4. Tarde: 16:00 - 18:00": return "16:00";
            default: return "";
        }
    }
    private String convertirFechaAMySQL(String fechaDDMMAAAA) {
    // Convierte "dd/mm/aaaa" a "aaaa-mm-dd"
    String[] partes = fechaDDMMAAAA.split("/");
    if (partes.length == 3) {
        return partes[2] + "-" + partes[1] + "-" + partes[0];
    }
    return fechaDDMMAAAA; // Si no puede convertir, devuelve la original
}

    private String obtenerHoraFin(String horario) {
        switch (horario) {
            case "1. Mañana: 08:00 - 10:00": return "10:00";
            case "2. Mañana: 10:00 - 12:00": return "12:00";
            case "3. Tarde: 14:00 - 16:00": return "16:00";
            case "4. Tarde: 16:00 - 18:00": return "18:00";
            default: return "";
        }
    }

    private void limpiarCampos() {
        comboClientes.setSelectedIndex(0);
        comboEntrenadores.setSelectedIndex(0);
        txtFecha.setText("");
        comboHorarios.setSelectedIndex(0);
        txtComentario.setText("");
    }
