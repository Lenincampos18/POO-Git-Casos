    private void configurarTabla() {
         modeloTabla = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Hacer que la tabla sea de solo lectura
            }
        };
        // Configurar el modelo de la tabla
        modeloTabla = new DefaultTableModel();
        modeloTabla.addColumn("ID");
        modeloTabla.addColumn("Cliente");
        modeloTabla.addColumn("Entrenador");
        modeloTabla.addColumn("Fecha");
        modeloTabla.addColumn("Horario");
        modeloTabla.addColumn("Comentario");
        
        tblReservas.setModel(modeloTabla);
    }
    
    private void cargarReservas() {
        modeloTabla.setRowCount(0); // Limpiar tabla
        
        List<Reserva> reservas = reservaDAO.listarReservas();
        
        for (Reserva reserva : reservas) {
            // Obtener nombres de cliente y entrenador
            String nombreCliente = obtenerNombreCliente(reserva.getIdCliente());
            String nombreEntrenador = obtenerNombreEntrenador(reserva.getIdEntrenador());
            String horario = reserva.getHoraInicio() + " - " + reserva.getHoraFin();
            String fechaFormateada = formatearFecha(reserva.getFecha());
            
            modeloTabla.addRow(new Object[]{
                "R" + String.format("%03d", reserva.getIdReserva()),
                nombreCliente,
                nombreEntrenador,
                fechaFormateada,
                horario,
                reserva.getComentario()
            });
        }
    }
    private String obtenerNombreCliente(int idCliente) {
        for (Cliente cliente : clienteDAO.obtenerClientes()) {
            if (cliente.getId() == idCliente) {
                return cliente.getNombre();
            }
        }
        return "Cliente no encontrado";
    }
     private String obtenerNombreEntrenador(int idEntrenador) {
        for (Entrenador entrenador : entrenadorDAO.listarEntrenadores()) {
            if (entrenador.getId() == idEntrenador) {
                return entrenador.getNombre();
            }
        }
        return "Entrenador no encontrado";
    }
    private String formatearFecha(String fechaMySQL) {
        // Convierte "2024-12-15" a "15/12/2024"
        if (fechaMySQL.contains("-")) {
            String[] partes = fechaMySQL.split("-");
            if (partes.length == 3) {
                return partes[2] + "/" + partes[1] + "/" + partes[0];
            }
        }
        return fechaMySQL;
    }

