    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String textoBusqueda = txtBuscar.getText().trim().toLowerCase();
        
        if (textoBusqueda.isEmpty()) {
            cargarReservas();
            return;
        }
        
        modeloTabla.setRowCount(0); // Limpiar tabla
        List<Reserva> reservas = reservaDAO.listarReservas();
        
        for (Reserva reserva : reservas) {
            String nombreCliente = obtenerNombreCliente(reserva.getIdCliente());
            String nombreEntrenador = obtenerNombreEntrenador(reserva.getIdEntrenador());
            String horario = reserva.getHoraInicio() + " - " + reserva.getHoraFin();
            String fechaFormateada = formatearFecha(reserva.getFecha());
            
            // Buscar en cliente, entrenador o comentario
            if (nombreCliente.toLowerCase().contains(textoBusqueda) ||
                nombreEntrenador.toLowerCase().contains(textoBusqueda) ||
                reserva.getComentario().toLowerCase().contains(textoBusqueda)) {
                
                modeloTabla.addRow(new Object[]{
                    "R" + String.format("%03d", reserva.getIdReserva()),
                    nombreCliente,
                    nombreEntrenador,
                    fechaFormateada,
                    horario,
                    reserva.getComentario()
                });
            }
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int filaSeleccionada = tblReservas.getSelectedRow();
        
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una reserva para eliminar");
            return;
        }
        
        // Obtener ID de la reserva seleccionada
        String idReservaStr = modeloTabla.getValueAt(filaSeleccionada, 0).toString();
        int idReserva = Integer.parseInt(idReservaStr.substring(1)); // Quitar la "R"
        
        int confirmacion = JOptionPane.showConfirmDialog(this,
            "¿Está seguro de eliminar la reserva " + idReservaStr + "?",
            "Confirmar Eliminación",
            JOptionPane.YES_NO_OPTION);
        
        if (confirmacion == JOptionPane.YES_OPTION) {
            if (reservaDAO.eliminarReserva(idReserva)) {
                JOptionPane.showMessageDialog(this, "Reserva eliminada exitosamente");
                cargarReservas(); // Recargar tabla
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar la reserva");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

